export function createOneHandedProfile(): TouchControlProfile {
  const profile = createDefaultProfile();
  profile.name = 'One-Handed Right';
  profile.description = 'All essential controls gathered on the right edge for thumb reach.';
  // Move camera stick to right side
  profile.widgets.camera_stick = {
    ...profile.widgets.camera_stick,
    anchor: 'BottomRight',
    offsetX: 0.18,
    offsetY: 0.08,
    width: 0.20,
    height: 0.20,
  };
  return profile;
}

export function createTabletProfile(): TouchControlProfile {
  const profile = createDefaultProfile();
  profile.name = 'Tablet / Large Screen';
  profile.description = 'Larger buttons spaced for comfortable two-handed tablet grip.';
  Object.keys(profile.widgets).forEach((k) => {
    profile.widgets[k].scale = 1.25;
  });
  return profile;
}
